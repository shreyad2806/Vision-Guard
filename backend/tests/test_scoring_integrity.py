class TestRepresentativeImageScores:
    """Analyze representative feature sets and verify logical score progression."""

    def _make_all_features(self, **overrides):
        """Create a full feature dict with sensible defaults, then override."""
        defaults = {
            "sharpness": 100, "brightness": 128, "contrast": 50,
            "noise_estimate": 10, "entropy": 6.0, "saturation": 35,
            "underexposure_pct": 3, "overexposure_pct": 2,
            "edge_density": 10, "dynamic_range": 120,
            "colorfulness": 25, "texture_complexity": 20,
        }
        defaults.update(overrides)
        return defaults

    def _analyze(self, features):
        model_feats = {k: features[k] for k in ["brightness", "contrast", "sharpness", "saturation", "edge_density"]}
        all_feats = features
        return predict_quality(model_feats, all_feats)

    def test_good_image_scores_higher_than_blurry(self):
        """A sharp image should score higher than a blurry one."""
        good = self._analyze(self._make_all_features(sharpness=250, brightness=130, contrast=55, noise_estimate=5))
        blurry = self._analyze(self._make_all_features(sharpness=10, brightness=130, contrast=55, noise_estimate=5))

        assert good["quality_score"] > blurry["quality_score"], (
            f"Good ({good['quality_score']}) should score higher than blurry ({blurry['quality_score']})"
        )

    def test_different_inputs_produce_different_scores(self):
        """Different feature sets produce different quality scores."""
        # Vary model-relevant features (brightness, contrast, sharpness, saturation, edge_density)
        a = self._analyze(self._make_all_features(brightness=128, sharpness=200, contrast=50, saturation=40, edge_density=25))
        b = self._analyze(self._make_all_features(brightness=30, sharpness=5, contrast=10, saturation=5, edge_density=1))

        assert a["quality_score"] != b["quality_score"], (
            f"Different inputs should produce different scores: a={a['quality_score']}, b={b['quality_score']}"
        )

    def test_extreme_features_differ_from_moderate(self):
        """Extreme feature values produce different scores from moderate ones."""
        moderate = self._analyze(self._make_all_features(brightness=200, sharpness=300, contrast=80, saturation=80, edge_density=30))
        extreme = self._analyze(self._make_all_features(brightness=20, sharpness=2, contrast=5, saturation=2, edge_density=0.5))

        assert moderate["quality_score"] != extreme["quality_score"], (
            f"Moderate ({moderate['quality_score']}) should differ from extreme ({extreme['quality_score']})"
        )

    def test_good_image_scores_higher_than_low_light(self):
        """A well-lit image should score higher than a low-light image."""
        lit = self._analyze(self._make_all_features(brightness=130, underexposure_pct=1))
        dark = self._analyze(self._make_all_features(brightness=35, underexposure_pct=50))

        assert lit["quality_score"] > dark["quality_score"]

    def test_readiness_degrades_with_more_issues(self):
        """More issues should reduce readiness score."""
        base_quality = 75.0

        r_clean = calculate_analytics_readiness(base_quality, [])
        r_one_issue = calculate_analytics_readiness(base_quality, [
            {"type": "insufficient_sharpness", "severity": "high"}
        ])
        r_many_issues = calculate_analytics_readiness(base_quality, [
            {"type": "insufficient_sharpness", "severity": "high"},
            {"type": "overexposure", "severity": "critical"},
            {"type": "image_noise", "severity": "high"},
        ])

        assert r_clean["score"] >= r_one_issue["score"] >= r_many_issues["score"]
        assert r_clean["score"] == base_quality  # No issues → no penalty

    def test_severity_affects_readiness_penalty(self):
        """Higher severity issues produce larger readiness penalties."""
        q = 80.0
        issues_low = [{"type": "insufficient_sharpness", "severity": "low"}]
        issues_high = [{"type": "insufficient_sharpness", "severity": "high"}]
        issues_critical = [{"type": "insufficient_sharpness", "severity": "critical"}]

        r_low = calculate_analytics_readiness(q, issues_low)
        r_high = calculate_analytics_readiness(q, issues_high)
        r_crit = calculate_analytics_readiness(q, issues_critical)

        assert r_low["score"] > r_high["score"] > r_crit["score"]
        assert r_low["blur_penalty"] < r_high["blur_penalty"] < r_crit["blur_penalty"]

    def test_context_impacts_vary_by_context(self):
        """Same issues produce different context impacts for different contexts."""
        issues = [{"type": "insufficient_sharpness", "severity": "high", "metric": "laplacian_variance",
                    "value": 30, "threshold": 40, "impact": "test", "confidence": 1.0}]

        impacts_traffic = get_context_impacts(issues, "Traffic Monitoring")
        impacts_crowd = get_context_impacts(issues, "Crowd Monitoring")

        # Both should have impacts for sharpness
        assert len(impacts_traffic) > 0
        assert len(impacts_crowd) > 0
        # But the text should differ
        assert impacts_traffic[0]["impact"] != impacts_crowd[0]["impact"]


