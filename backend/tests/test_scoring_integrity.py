class TestReadinessIndependence:
    """Verify that analytics_readiness_score is NOT simply quality_score renamed."""

    def test_readiness_differs_from_quality_with_issues(self):
        """When issues exist, readiness < quality_score due to penalties."""
        quality_score = 80.0
        issues = [
            {"type": "insufficient_sharpness", "severity": "high", "metric": "laplacian_variance", "value": 30, "threshold": 40, "impact": "test", "confidence": 1.0},
            {"type": "underexposure", "severity": "moderate", "metric": "dark_pixel_ratio", "value": 20, "threshold": 25, "impact": "test", "confidence": 1.0},
        ]

        readiness = calculate_analytics_readiness(quality_score, issues)

        assert readiness["score"] < quality_score, (
            f"Readiness ({readiness['score']}) should be less than quality ({quality_score}) "
            f"when issues are present"
        )

    def test_readiness_penalties_are_computed_from_issues(self):
        """Penalties are derived from issue types and severities."""
        quality_score = 80.0
        issues_blur = [{"type": "severe_blur", "severity": "critical"}]
        issues_none = []

        r_blur = calculate_analytics_readiness(quality_score, issues_blur)
        r_none = calculate_analytics_readiness(quality_score, issues_none)

        # Blur penalty should reduce readiness
        assert r_blur["score"] < r_none["score"]
        assert r_blur["blur_penalty"] > 0
        assert r_none["blur_penalty"] == 0

    def test_readiness_status_maps_correctly(self):
        """Status labels match score thresholds."""
        assert get_readiness_status(95) == "HIGHLY READY"
        assert get_readiness_status(80) == "HIGHLY READY"
        assert get_readiness_status(70) == "READY"
        assert get_readiness_status(60) == "READY"
        assert get_readiness_status(50) == "LIMITED READINESS"
        assert get_readiness_status(40) == "LIMITED READINESS"
        assert get_readiness_status(30) == "NOT READY"
        assert get_readiness_status(20) == "NOT READY"
        assert get_readiness_status(10) == "CRITICAL / REJECT"
        assert get_readiness_status(0) == "CRITICAL / REJECT"

    def test_readiness_score_never_negative(self):
        """Readiness score is clamped to [0, 100]."""
        quality_score = 5.0
        issues = [
            {"type": "severe_blur", "severity": "critical"},
            {"type": "underexposure", "severity": "critical"},
            {"type": "image_noise", "severity": "critical"},
            {"type": "severe_visual_degradation", "severity": "critical"},
            {"type": "low_contrast", "severity": "critical"},
        ]

        readiness = calculate_analytics_readiness(quality_score, issues)

        assert readiness["score"] >= 0
        assert readiness["score"] <= 100

    def test_readiness_details_contain_all_penalty_fields(self):
        """The API response includes all 6 readiness detail fields."""
        readiness = calculate_analytics_readiness(70.0, [])
        details = readiness

        assert "base_quality_score" in details
        assert "blur_penalty" in details
        assert "exposure_penalty" in details
        assert "noise_penalty" in details
        assert "corruption_penalty" in details
        assert "information_penalty" in details
        assert details["base_quality_score"] == 70.0

    def test_different_issue_types_apply_different_penalties(self):
        """Different issue types contribute to different penalty categories."""
        quality_score = 80.0

        r_blur = calculate_analytics_readiness(quality_score, [{"type": "severe_blur", "severity": "high"}])
        r_exposure = calculate_analytics_readiness(quality_score, [{"type": "overexposure", "severity": "high"}])
        r_noise = calculate_analytics_readiness(quality_score, [{"type": "image_noise", "severity": "high"}])

        assert r_blur["blur_penalty"] > 0
        assert r_exposure["exposure_penalty"] > 0
        assert r_noise["noise_penalty"] > 0

        # Each should only penalize its own category
        assert r_blur["exposure_penalty"] == 0
        assert r_exposure["blur_penalty"] == 0
        assert r_noise["blur_penalty"] == 0

    def test_readiness_is_independent_from_quality_label(self):
        """Readiness status is independent of quality label."""
        # Two images with same quality_score but different issues
        q = 65.0
        issues_a = [{"type": "insufficient_sharpness", "severity": "high"}]
        issues_b = [{"type": "underexposure", "severity": "critical"}]

        r_a = calculate_analytics_readiness(q, issues_a)
        r_b = calculate_analytics_readiness(q, issues_b)

        # Both start from same quality but have different penalties
        assert r_a["base_quality_score"] == r_b["base_quality_score"] == 65.0
        # Penalties differ by issue type
        assert r_a["blur_penalty"] != r_b["exposure_penalty"] or r_a["score"] != r_b["score"]


