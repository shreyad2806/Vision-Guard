class TestIssueConfidence:
    """Verify that issue confidence is computed by detect_issues(), not hard-coded."""

    def test_confidence_values_from_detector(self):
        """detect_issues returns confidence values that reflect detection certainty."""
        # Clean image — no issues expected
        clean_features = {
            "sharpness": 200, "brightness": 128, "contrast": 50,
            "noise_estimate": 5, "entropy": 6.5, "saturation": 40,
            "underexposure_pct": 2, "overexposure_pct": 1,
            "edge_density": 12, "dynamic_range": 150,
            "colorfulness": 30, "texture_complexity": 25,
        }
        issues = detect_issues(clean_features)
        assert len(issues) == 0

    def test_confidence_is_float_between_0_and_1(self):
        """All issue confidence values are floats in [0, 1]."""
        bad_features = {
            "sharpness": 3, "brightness": 30, "contrast": 8,
            "noise_estimate": 45, "entropy": 1.5, "saturation": 2,
            "underexposure_pct": 55, "overexposure_pct": 0,
            "edge_density": 0.3, "dynamic_range": 10,
            "colorfulness": 1, "texture_complexity": 0.3,
        }
        issues = detect_issues(bad_features)

        for issue in issues:
            assert "confidence" in issue
            assert 0.0 <= issue["confidence"] <= 1.0, (
                f"Issue '{issue['type']}' has confidence {issue['confidence']} "
                f"outside [0, 1]"
            )

    def test_confidence_varies_by_issue_type(self):
        """Different issue types have different confidence levels."""
        bad_features = {
            "sharpness": 3, "brightness": 30, "contrast": 8,
            "noise_estimate": 45, "entropy": 1.5, "saturation": 2,
            "underexposure_pct": 55, "overexposure_pct": 0,
            "edge_density": 0.3, "dynamic_range": 10,
            "colorfulness": 1, "texture_complexity": 0.3,
        }
        issues = detect_issues(bad_features)
        confidences = {i["type"]: i["confidence"] for i in issues}

        # severe_blur should have confidence 1.0 (deterministic threshold)
        if "severe_blur" in confidences:
            assert confidences["severe_blur"] == 1.0

        # image_noise should have confidence 1.0
        if "image_noise" in confidences:
            assert confidences["image_noise"] == 1.0

        # potential_visual_defect should have confidence 0.85
        if "potential_visual_defect" in confidences:
            assert confidences["potential_visual_defect"] == 0.85

    def test_issue_fields_contain_actual_metric_values(self):
        """Issues contain real metric value and threshold from detection."""
        features = {
            "sharpness": 25, "brightness": 100, "contrast": 40,
            "noise_estimate": 20, "entropy": 5, "saturation": 30,
            "underexposure_pct": 5, "overexposure_pct": 5,
            "edge_density": 8, "dynamic_range": 100,
            "colorfulness": 20, "texture_complexity": 20,
        }
        issues = detect_issues(features)

        for issue in issues:
            assert "metric" in issue
            assert "value" in issue
            assert "threshold" in issue
            assert isinstance(issue["value"], float)
            assert isinstance(issue["threshold"], float)

    def test_issue_value_reflects_actual_feature(self):
        """The 'value' in an issue matches the actual feature value."""
        features = {
            "sharpness": 25.0,
            "brightness": 60.0,
            "contrast": 40.0,
            "noise_estimate": 20.0,
            "entropy": 5.0,
            "saturation": 30.0,
            "underexposure_pct": 20.0,
            "overexposure_pct": 12.0,
            "edge_density": 8.0,
            "dynamic_range": 100.0,
            "colorfulness": 20.0,
            "texture_complexity": 20.0,
        }
        issues = detect_issues(features)

        # Find the sharpness issue
        sharpness_issues = [i for i in issues if i["metric"] == "laplacian_variance"]
        for si in sharpness_issues:
            assert si["value"] == 25.0, (
                f"Sharpness issue value {si['value']} != actual 25.0"
            )


