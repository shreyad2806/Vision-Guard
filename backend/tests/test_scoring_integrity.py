class TestNoHardCodedValues:
    """Verify no scores or recommendations are hard-coded in production code."""

    def test_backend_inference_has_no_hardcoded_scores(self):
        """predict_quality does not return a fixed score for all inputs."""
        results = []
        for brightness in [30, 100, 200]:
            for sharpness in [5, 100, 250]:
                feats = {"brightness": brightness, "contrast": 40, "sharpness": sharpness, "saturation": 30, "edge_density": 0.10}
                all_f = {"sharpness": sharpness, "brightness": brightness, "contrast": 40, "noise_estimate": 10, "entropy": 5,
                         "saturation": 30, "underexposure_pct": 5, "overexposure_pct": 5, "edge_density": 8, "dynamic_range": 80,
                         "colorfulness": 15, "texture_complexity": 15}
                result = predict_quality(feats, all_f)
                results.append(result["quality_score"])

        unique_scores = set(results)
        assert len(unique_scores) > 1, (
            f"predict_quality returned the same score for all inputs: {unique_scores}"
        )

    def test_readiness_is_not_copied_from_quality(self):
        """readiness_score ≠ quality_score when issues exist."""
        for qs in [30.0, 50.0, 70.0, 90.0]:
            issues = [{"type": "insufficient_sharpness", "severity": "high"}]
            readiness = calculate_analytics_readiness(qs, issues)
            assert readiness["score"] != qs, (
                f"Readiness {readiness['score']} should not equal quality {qs} "
                f"when blur issue is present"
            )

    def test_calculator_band_mapping_not_hardcoded_per_image(self):
        """Quality bands are defined globally, not per-image."""
        # All scores in [80, 100] should map to "Excellent"
        for score in [80, 85, 90, 95, 100]:
            assessment = get_quality_assessment(float(score))
            assert assessment["label"] == "Excellent"

        # All scores in [0, 19] should map to "Critical"
        for score in [0, 5, 10, 15, 19]:
            assessment = get_quality_assessment(float(score))
            assert assessment["label"] == "Critical"

    def test_recommendations_match_quality_bands(self):
        """Recommendations are derived from quality score, not image-specific."""
        for score in [90, 70, 50, 30, 10]:
            rec = get_quality_recommendation(float(score))
            assert isinstance(rec, str)
            assert len(rec) > 10

    def test_explainability_uses_actual_issue_data(self):
        """Explanations reference the actual issue's metric and threshold."""
        issues = [{
            "type": "image_noise",
            "severity": "high",
            "metric": "noise_estimate",
            "value": 22.5,
            "threshold": 15.0,
            "impact": "noise impact",
            "confidence": 1.0,
        }]
        explanations = generate_issue_explanations(issues)

        assert len(explanations) == 1
        exp = explanations[0]
        assert exp["evidence"]["metric"] == "noise_estimate"
        assert exp["evidence"]["value"] == 22.5
        assert exp["evidence"]["threshold"] == 15.0
        assert "noise" in exp["issue"].lower() or "noise" in exp["recommendation"].lower()

    def test_frontend_source_has_no_hardcoded_scores(self):
        """Production frontend components do not contain hard-coded scores."""
        frontend_dir = Path(__file__).parent.parent.parent / "frontend" / "src" / "components"
        if not frontend_dir.exists():
            pytest.skip("Frontend directory not found")

        # Components that should NOT have hard-coded scores
        component_files = [
            "analysis/AnalysisResult.tsx",
            "analysis/QualityScore.tsx",
            "analysis/IssueCard.tsx",
            "analysis/AnalyticsReadiness.tsx",
        ]

        for rel_path in component_files:
            fpath = frontend_dir / rel_path
            if not fpath.exists():
                continue
            content = fpath.read_text()
            # Should not contain hard-coded numeric scores
            # (exception: mathematical constants like 100 for /100)
            lines = content.split("\n")
            for i, line in enumerate(lines):
                stripped = line.strip()
                # Skip comments, imports, CSS values, SVG viewBox
                if stripped.startswith("//") or stripped.startswith("import") or "viewBox" in stripped:
                    continue
                # Check for patterns like quality_score: 85 or readiness: 42
                if any(pat in stripped for pat in ["quality_score:", "readiness_score:", "analysis_confidence:"]):
                    if any(c.isdigit() for c in stripped.split(":")[-1]):
                        pytest.fail(
                            f"Possible hard-coded score in {rel_path}:{i+1}: {stripped}"
                        )


