class TestQualityScoreGeneration:
    """Verify that quality_score is computed dynamically from features."""

    def test_model_path_changes_score(self):
        """Different input features produce different quality scores."""
        # Use widely different feature values to ensure the model differentiates
        features_a = {"brightness": 200, "contrast": 80, "sharpness": 300, "saturation": 80, "edge_density": 0.40}
        features_b = {"brightness": 20, "contrast": 5, "sharpness": 2, "saturation": 2, "edge_density": 0.001}

        all_a = {"sharpness": 300, "brightness": 200, "contrast": 80, "noise_estimate": 5, "entropy": 6.5, "saturation": 80,
                 "underexposure_pct": 2, "overexposure_pct": 1, "edge_density": 30, "dynamic_range": 150, "colorfulness": 30, "texture_complexity": 25}
        all_b = {"sharpness": 2, "brightness": 20, "contrast": 5, "noise_estimate": 50, "entropy": 1, "saturation": 2,
                 "underexposure_pct": 60, "overexposure_pct": 0, "edge_density": 0.2, "dynamic_range": 10, "colorfulness": 1, "texture_complexity": 0.5}

        result_a = predict_quality(features_a, all_a)
        result_b = predict_quality(features_b, all_b)

        # Scores must differ between different inputs
        assert result_a["quality_score"] != result_b["quality_score"], (
            f"Quality scores should differ for different inputs: "
            f"input_a={result_a['quality_score']}, input_b={result_b['quality_score']}"
        )

    def test_quality_score_comes_from_pipeline_not_copy(self):
        """quality_score and analytics_readiness_score are NOT the same value."""
        features = {"brightness": 100, "contrast": 40, "sharpness": 80, "saturation": 30, "edge_density": 0.10}
        all_feats = {"sharpness": 80, "brightness": 100, "contrast": 40, "noise_estimate": 12, "entropy": 5.5, "saturation": 30,
                     "underexposure_pct": 8, "overexposure_pct": 3, "edge_density": 8, "dynamic_range": 100, "colorfulness": 20, "texture_complexity": 18}

        result = predict_quality(features, all_feats)

        # They can be different (readiness = quality - penalties)
        # They are only equal when there are zero issues
        issues = detect_issues(all_feats)
        if issues:
            assert result["quality_score"] != result["analytics_readiness_score"], (
                f"With {len(issues)} issues, quality_score ({result['quality_score']}) "
                f"should differ from readiness_score ({result['analytics_readiness_score']})"
            )

    def test_fallback_score_depends_on_features(self):
        """The rule-based fallback score changes with different features."""
        feats_a = {"sharpness": 300, "brightness": 128, "contrast": 50, "saturation": 100, "edge_density": 0.5}
        feats_b = {"sharpness": 0, "brightness": 0, "contrast": 0, "saturation": 0, "edge_density": 0}

        score_a = _fallback_score(feats_a)
        score_b = _fallback_score(feats_b)

        assert score_a > score_b
        assert 0 <= score_a <= 100
        assert 0 <= score_b <= 100

    def test_confidence_estimation_is_dynamic(self):
        """analysis_confidence varies based on model tree agreement."""
        # When model is loaded, confidence comes from _estimate_confidence
        # When no model, it returns 70.0 (rule-based fallback)
        features = {"brightness": 128, "contrast": 50, "sharpness": 200, "saturation": 40, "edge_density": 0.15}
        all_feats = {"sharpness": 200, "brightness": 128, "contrast": 50, "noise_estimate": 5, "entropy": 6.5, "saturation": 40,
                     "underexposure_pct": 2, "overexposure_pct": 1, "edge_density": 12, "dynamic_range": 150, "colorfulness": 30, "texture_complexity": 25}

        result = predict_quality(features, all_feats)
        # Confidence is a float between 0 and 100
        assert isinstance(result["analysis_confidence"], float)
        assert 0 <= result["analysis_confidence"] <= 100

    def test_raw_prediction_is_independent(self):
        """raw_prediction is the model's output before calibration."""
        features = {"brightness": 128, "contrast": 50, "sharpness": 200, "saturation": 40, "edge_density": 0.15}
        all_feats = {"sharpness": 200, "brightness": 128, "contrast": 50, "noise_estimate": 5, "entropy": 6.5, "saturation": 40,
                     "underexposure_pct": 2, "overexposure_pct": 1, "edge_density": 12, "dynamic_range": 150, "colorfulness": 30, "texture_complexity": 25}

        result = predict_quality(features, all_feats)
        assert "raw_prediction" in result
        assert isinstance(result["raw_prediction"], float)
        # raw_prediction may differ from quality_score after calibration
        # (they can also be close, but we verify the field exists and is numeric)


